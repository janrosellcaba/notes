const dictionaries: Record<Locale, Record<MessageKey, string>> = { en, ca, es };

function readLocale(): Locale {
  try {
    const value = localStorage.getItem(KEY);
    if (value === "ca" || value === "es" || value === "en") return value;
  } catch {
    // Ignore storage failures.
  }
  return "en";
}

type I18nValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, vars?: Record<string, string>) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(readLocale);
  useEffect(() => {
    document.documentElement.lang = locale === "en" ? "en-GB" : locale;
  }, [locale]);
  const value = useMemo<I18nValue>(() => {
    function setLocale(next: Locale) {
      setLocaleState(next);
      try {
        localStorage.setItem(KEY, next);
      } catch {
        // The choice still applies for this visit.
      }
    }
    function t(key: MessageKey, vars?: Record<string, string>) {
      let text = dictionaries[locale][key] ?? en[key];
      if (vars) {
        for (const [name, replacement] of Object.entries(vars)) {
          text = text.replaceAll(`{${name}}`, replacement);
        }
      }
      return text;
    }
    return { locale, setLocale, t };
  }, [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
